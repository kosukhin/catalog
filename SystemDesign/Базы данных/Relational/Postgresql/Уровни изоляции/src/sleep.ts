/**
 * Ожидание внутри асинхронного кода.
 *
 * Нужно в двух местах: барьер опрашивает каталог с маркерами, а повтор
 * транзакции после конфликта выжидает небольшую паузу, чтобы два агента не
 * столкнулись снова ровно в тот же момент.
 *
 * @param ms сколько ждать, миллисекунды
 */
export function sleep(ms: number): Promise<void> {
    return new Promise((resolve) => {
        setTimeout(resolve, ms);
    });
}
