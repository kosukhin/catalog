-- Схема учебного банка.
--
-- Здесь нет триггеров и хранимых процедур: баланс — это просто число в поле
-- accounts.balance, а всё «перевод денег» делает приложение. Именно поэтому
-- корректность итога зависит от уровня изоляции транзакций и от того, читает
-- ли приложение строку повторно или перезаписывает её вслепую.

-- Пользователи банка.
CREATE TABLE users (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL
);

-- Счета. Баланс — целое число рублей (никаких денежных типов: в примере важно
-- только то, что число читается и записывается двумя транзакциями).
CREATE TABLE accounts (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title   text NOT NULL,
    balance integer NOT NULL CHECK (balance >= 0)
);

-- Владельцы счёта. Счёт может быть общим: тогда у него несколько пользователей,
-- и каждый из них может списывать и зачислять через своего агента.
CREATE TABLE account_members (
    account_id integer NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (account_id, user_id)
);

-- Журнал проводок: что агент прочитал и что записал. Живёт внутри той же
-- транзакции, что и UPDATE баланса, поэтому откат убирает и запись журнала.
CREATE TABLE operations (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     integer NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    agent          text NOT NULL,
    kind           text NOT NULL,
    amount         integer NOT NULL,
    balance_before integer NOT NULL,
    balance_after  integer NOT NULL,
    isolation      text NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX operations_account_id_idx ON operations (account_id, id);
