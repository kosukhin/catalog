// Фича: оператор возведения в степень **
console.log("=== 02. Оператор ** ===");

console.log("3 ** 4 =", 3 ** 4);        // 81
console.log("2 ** -2 =", 2 ** -2);      // 0.25
console.log("2 ** 0.5 =", 2 ** 0.5);    // √2

// Правоассоциативность: a ** b ** c === a ** (b ** c)
console.log("2 ** 3 ** 2 =", 2 ** 3 ** 2, "(= 2 ** 9 =", 2 ** 9, ")");

// Сравнение с Math.pow — результаты идентичны
console.log("равно Math.pow:", (2 ** 10) === Math.pow(2, 10));

// Комбинируется с присваиванием
let x = 2;
x **= 5;
console.log("x **= 5:", x); // 32
